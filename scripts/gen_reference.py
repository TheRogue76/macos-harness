#!/usr/bin/env python3
"""Writes docs/reference/cli.md from the CLI's --help and docs/reference/mcp.md from the MCP
server's instructions and tool schemas, so the reference can't drift from the code.

Usage:
    python3 scripts/gen_reference.py [--cli PATH] [--check]

--cli names the macos-harness binary (default: the debug build, from `swift build
--show-bin-path`). --check writes nothing and exits 1 when the files on disk are out of date.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
COLUMNS = "100"
HEADER = "<!-- Generated by scripts/gen_reference.py from {source}. Don't edit by hand. -->\n\n"


def run(cli, args, stdin=None):
    env = dict(os.environ, COLUMNS=COLUMNS)
    result = subprocess.run([cli, *args], input=stdin, capture_output=True, text=True, env=env, timeout=60)
    if result.returncode != 0:
        sys.exit(f"{' '.join([cli, *args])} failed: {result.stderr.strip()}")
    return result.stdout


def subcommands(help_text):
    names = []
    inside = False
    for line in help_text.splitlines():
        if line.startswith("SUBCOMMANDS:"):
            inside = True
            continue
        if inside:
            if not line.strip():
                break
            match = re.match(r"^  ([a-z][a-z0-9-]*)(?: |$)", line)
            if match:
                names.append(match.group(1))
    return names


def commands(cli, path=()):
    text = run(cli, [*path, "--help"])
    yield path, text
    for name in subcommands(text):
        if name not in path and len(path) < 3:
            yield from commands(cli, (*path, name))


def cli_reference(cli):
    parts = [
        HEADER.format(source="`macos-harness <command> --help`"),
        "# CLI reference\n\n",
        "Every command, as `--help` prints it. Every command takes `--json`; the values that stay "
        "stable are in the [interface contract](../../knowledge/design/interface-contract.md).\n\n",
    ]
    entries = list(commands(cli))
    parts.append("".join(f"- [`{' '.join(('macos-harness', *path))}`](#{anchor(path)})\n" for path, _ in entries[1:]))
    for path, text in entries:
        title = " ".join(("macos-harness", *path))
        parts.append(f"\n## {title}\n\n```text\n{text.rstrip()}\n```\n")
    return "".join(parts)


def anchor(path):
    return re.sub(r"[^a-z0-9 -]", "", " ".join(("macos-harness", *path)).lower()).replace(" ", "-")


def mcp_session(cli):
    requests = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
            "protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "gen_reference", "version": "1"},
        }},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
    ]
    output = run(cli, ["mcp"], stdin="".join(json.dumps(request) + "\n" for request in requests))
    replies = {reply["id"]: reply["result"] for reply in map(json.loads, output.splitlines()) if "result" in reply}
    return replies[1], replies[2]["tools"]


def kind(schema):
    if "enum" in schema:
        return " | ".join(f"`{value}`" for value in schema["enum"])
    if schema.get("type") == "array":
        return f"array of {schema.get('items', {}).get('type', 'values')}"
    if schema.get("type") == "object" and "additionalProperties" in schema:
        return f"object of {schema['additionalProperties'].get('type', 'values')}"
    return schema.get("type", "")


def prose(text):
    pieces = text.split("`")
    return "`".join(piece if index % 2 else piece.replace("<", "\\<") for index, piece in enumerate(pieces))


def cell(text):
    return prose(text).replace("|", "\\|").replace("\n", " ")


def mcp_reference(cli):
    initialized, tools = mcp_session(cli)
    parts = [
        HEADER.format(source="`macos-harness mcp` (initialize and tools/list)"),
        "# MCP reference\n\n",
        "The tools `macos-harness mcp` serves, with each parameter. Errors end with `(error N)`; the "
        "codes are in the [interface contract](../../knowledge/design/interface-contract.md).\n\n",
        "".join(f"- [`{tool['name']}`](#{tool['name']}): {tool.get('title', '')}\n" for tool in tools),
        "\n## Instructions\n\nWhat the server tells an agent when it connects:\n\n",
        "> " + prose(initialized.get("instructions", "").strip()).replace("\n", "\n> ") + "\n",
    ]
    for tool in tools:
        hints = tool.get("annotations", {})
        reads = " Read only." if hints.get("readOnlyHint") else ""
        parts.append(f"\n## {tool['name']}\n\n**{tool.get('title', '')}.**{reads} {prose(tool['description'])}\n")
        schema = tool.get("inputSchema", {})
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not properties:
            parts.append("\nNo parameters.\n")
            continue
        parts.append("\n| Parameter | Type | Description |\n| --- | --- | --- |\n")
        for name in sorted(properties, key=lambda key: (key not in required, key)):
            prop = properties[name]
            label = f"`{name}`" + (" (required)" if name in required else "")
            parts.append(f"| {label} | {cell(kind(prop))} | {cell(prop.get('description', ''))} |\n")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cli")
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    cli = options.cli or str(Path(subprocess.check_output(
        ["swift", "build", "--show-bin-path"], cwd=ROOT, text=True
    ).strip()) / "macos-harness")
    files = {OUT / "cli.md": cli_reference(cli), OUT / "mcp.md": mcp_reference(cli)}
    stale = [path for path, text in files.items() if not path.exists() or path.read_text() != text]
    if options.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date; run python3 scripts/gen_reference.py", file=sys.stderr)
        sys.exit(1 if stale else 0)
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
    print(f"Wrote {len(files)} files, {len(stale)} changed.")


if __name__ == "__main__":
    main()
